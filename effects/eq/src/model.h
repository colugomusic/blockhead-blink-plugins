#pragma once

#include "filters.hpp"
#include <blink/plugin-impl.hpp>
#include <variant>

namespace eq {

static inline constexpr auto BAND_COUNT = 8;

struct Params {
	struct {
		std::array<blink_ParamIdx, 8> band_on;
		std::array<blink_ParamIdx, 8> band_curve;
	} option;
	struct {
		std::array<blink_ParamIdx, 8> band_freq;
		std::array<blink_ParamIdx, 8> band_gain;
		std::array<blink_ParamIdx, 8> band_slope;
		std::array<blink_ParamIdx, 8> band_bandwidth;
	} slider;
};

struct UnitDSP {
	blink_SR SR;
	blink::BlockPositions block_positions;
};

using Instance = blink::Instance<>;
using Unit     = blink::Unit<UnitDSP>;

using fr_filter_coeffs_var = std::variant<
	std::monostate,
	filters::shelving::band_shelf::coeffs<float>,
	filters::shelving::hi_shelf::coeffs<float>,
	filters::shelving::lo_shelf::coeffs<float>
>;

struct fr_band_data {
	fr_filter_coeffs_var coeffs;
};

struct fr_data {
	std::array<fr_band_data, BAND_COUNT> bands;
};

template <size_t N> constexpr
auto make_no_params() -> std::array<blink_ParamIdx, N> {
	std::array<blink_ParamIdx, N> arr{};
	arr.fill(blink_ParamIdx{-1});
	return arr;
}

template <size_t N>
constexpr auto NO_PARAMS = make_no_params<N>();

struct param_settings {
	std::vector<blink_ParamIdx> visible_params;
	std::array<blink_ParamIdx, BAND_COUNT> fr_enabled               = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_frequency             = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_left_vertical         = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_right_horizontal      = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_right_vertical        = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_left_horizontal_ctrl  = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_left_vertical_ctrl    = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_right_horizontal_ctrl = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> fr_right_vertical_ctrl   = NO_PARAMS<BAND_COUNT>;
	std::array<std::vector<blink_ParamIdx>, BAND_COUNT> fr_extra;
	blink_FrequencyResponseInfo fr_info = {0};
};

struct Model {
	blink::Plugin plugin;
	blink::Entities<Instance, Unit> entities;
	Params params;
	// Frequency response data generated by the most recent call to blink_get_frequency_response_data().
	eq::fr_data fr_data;
	// Parameter settings generated by the most recent call to blink_get_param_settings().
	eq::param_settings param_settings;
};

} // namespace eq
