#pragma once

#include "filters.hpp"
#include <blink/plugin-impl.hpp>
#include <variant>

namespace eq {

static inline constexpr auto BAND_COUNT    = 8;
static inline constexpr auto CHANNEL_COUNT = 2;

struct Params {
	struct {
		std::array<blink_ParamIdx, BAND_COUNT> band_on;
		std::array<blink_ParamIdx, BAND_COUNT> band_curve;
	} option;
	struct {
		std::array<blink_ParamIdx, BAND_COUNT> band_freq;
		std::array<blink_ParamIdx, BAND_COUNT> band_gain;
		std::array<blink_ParamIdx, BAND_COUNT> band_slope;
		std::array<blink_ParamIdx, BAND_COUNT> band_bandwidth;
	} slider;
};

struct band_shelf_filter {
	// Blockhead likes to rudely and suddenly start throwing audio at filters
	// without giving them a chance to settle first which can cause glitches at
	// extreme parameter values so we set these flags to true after a reset and
	// then give the filters a chance to settle the first time they are used.
	bool settled = false;
	snd::filters::shelving::band_shelf::state state;
};

struct band_pass_filter {
	bool settled = false;
	snd::filters::shelving::band_pass::state state;
};

struct hi_shelf_filter {
	bool settled = false;
	snd::filters::shelving::hi_shelf::state state;
};

struct lo_shelf_filter {
	bool settled = false;
	snd::filters::shelving::lo_shelf::state state;
};

struct band_dsp {
	band_shelf_filter band_shelf;
	band_pass_filter band_pass;
	hi_shelf_filter hi_shelf;
	lo_shelf_filter lo_shelf;
};

struct channel_dsp {
	std::array<eq::band_dsp, BAND_COUNT> bands;
};

struct UnitDSP {
	blink_SR SR;
	blink::BlockPositions block_positions;
	std::array<channel_dsp, CHANNEL_COUNT> channels;
};

using Instance = blink::Instance<>;
using Unit     = blink::Unit<UnitDSP>;

using fr_filter_coeffs_var = std::variant<
	std::monostate,
	snd::filters::shelving::band_shelf::coeffs,
	snd::filters::shelving::band_pass::coeffs,
	snd::filters::shelving::hi_shelf::coeffs,
	snd::filters::shelving::lo_shelf::coeffs
>;

struct fr_band_data {
	fr_filter_coeffs_var coeffs;
};

struct fr_data {
	std::array<fr_band_data, BAND_COUNT> bands;
};

template <size_t N> constexpr
auto make_no_params() -> std::array<blink_ParamIdx, N> {
	std::array<blink_ParamIdx, N> arr{};
	arr.fill(blink_ParamIdx{-1});
	return arr;
}

template <size_t N>
constexpr auto NO_PARAMS = make_no_params<N>();

struct fr_info {
	std::array<std::vector<blink_ParamIdx>, BAND_COUNT> extra_params;
	std::array<blink_ParamIdxArray, BAND_COUNT> extra_params_c;
	std::array<blink_ParamIdx, BAND_COUNT> enabled                  = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> frequency                = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> mb_left_vertical         = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> mb_right_horizontal      = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> mb_left_horizontal_ctrl  = NO_PARAMS<BAND_COUNT>;
	std::array<blink_ParamIdx, BAND_COUNT> mb_left_vertical_ctrl    = NO_PARAMS<BAND_COUNT>;
};

struct param_settings {
	std::vector<blink_ParamIdx> visible_params;
	eq::fr_info fr_info;
};

struct param_settings_c {
	blink_FrequencyResponseInfo fr_info = {0};
};

struct Model {
	blink::Plugin plugin;
	blink::Entities<Instance, Unit> entities;
	Params params;
	// Frequency response data generated by the most recent call to blink_get_frequency_response_data().
	eq::fr_data fr_data;
	// Parameter settings generated by the most recent call to blink_get_param_settings().
	eq::param_settings param_settings;
	eq::param_settings_c param_settings_c;
};

} // namespace eq
